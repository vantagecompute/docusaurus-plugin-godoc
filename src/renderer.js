/**
 * Renders parsed Go doc structures into Docusaurus-compatible Markdown pages.
 */

function renderPackagePage(parsed, pkgName, pkgLabel) {
  const lines = [];

  lines.push('---');
  lines.push(`title: "Package: ${pkgLabel}"`);
  lines.push(`description: "Go package documentation for ${pkgName}"`);
  lines.push('---');
  lines.push('');
  lines.push(`# Package \`${pkgLabel}\``);
  lines.push('');
  lines.push('{/* Auto-generated by @vantagecompute/docusaurus-plugin-godoc. Do not edit manually. */}');
  lines.push('');

  if (parsed.overview) {
    lines.push('## Overview');
    lines.push('');
    lines.push(parsed.overview);
    lines.push('');
  }

  if (parsed.constants.length > 0) {
    lines.push('## Constants');
    lines.push('');
    for (const c of parsed.constants) {
      lines.push('```go');
      lines.push(c.declaration);
      lines.push('```');
      lines.push('');
      if (c.doc) {
        lines.push(c.doc);
        lines.push('');
      }
    }
  }

  if (parsed.variables.length > 0) {
    lines.push('## Variables');
    lines.push('');
    for (const v of parsed.variables) {
      lines.push('```go');
      lines.push(v.declaration);
      lines.push('```');
      lines.push('');
      if (v.doc) {
        lines.push(v.doc);
        lines.push('');
      }
    }
  }

  if (parsed.functions.length > 0) {
    lines.push('## Functions');
    lines.push('');
    for (const f of parsed.functions) {
      lines.push(`### ${f.name}`);
      lines.push('');
      lines.push('```go');
      lines.push(f.signature);
      lines.push('```');
      lines.push('');
      if (f.doc) {
        lines.push(f.doc);
        lines.push('');
      }
    }
  }

  if (parsed.types.length > 0) {
    lines.push('## Types');
    lines.push('');
    for (const t of parsed.types) {
      lines.push(`### ${t.name}`);
      lines.push('');
      lines.push('```go');
      lines.push(t.declaration);
      lines.push('```');
      lines.push('');
      if (t.doc) {
        lines.push(t.doc);
        lines.push('');
      }

      if (t.constructors && t.constructors.length > 0) {
        lines.push(`#### Constructors`);
        lines.push('');
        for (const c of t.constructors) {
          lines.push(`##### ${c.name}`);
          lines.push('');
          lines.push('```go');
          lines.push(c.signature);
          lines.push('```');
          lines.push('');
          if (c.doc) {
            lines.push(c.doc);
            lines.push('');
          }
        }
      }

      if (t.methods.length > 0) {
        lines.push(`#### Methods on ${t.name}`);
        lines.push('');
        for (const m of t.methods) {
          lines.push(`##### ${m.name}`);
          lines.push('');
          lines.push('```go');
          lines.push(m.signature);
          lines.push('```');
          lines.push('');
          if (m.doc) {
            lines.push(m.doc);
            lines.push('');
          }
        }
      }
    }
  }

  return lines.join('\n');
}

function renderIndexPage(packageDocs) {
  const lines = [];

  lines.push('---');
  lines.push('title: SDK Reference');
  lines.push('description: "Auto-generated Go package documentation"');
  lines.push('---');
  lines.push('');
  lines.push('# SDK Reference');
  lines.push('');
  lines.push('{/* Auto-generated by @vantagecompute/docusaurus-plugin-godoc. Do not edit manually. */}');
  lines.push('');
  lines.push('Auto-generated documentation from Go source comments.');
  lines.push('');
  lines.push('## Packages');
  lines.push('');
  lines.push('| Package | Types | Functions | Description |');
  lines.push('|---------|-------|-----------|-------------|');

  for (const pkg of packageDocs) {
    const desc = pkg.overview ? pkg.overview.split('\n')[0].substring(0, 80) : '';
    const link = `./${pkg.filename}`;
    lines.push(`| [${pkg.label}](${link}) | ${pkg.types} | ${pkg.functions} | ${desc} |`);
  }

  lines.push('');
  lines.push('## Regenerating');
  lines.push('');
  lines.push('SDK reference pages are generated at build time by `@vantagecompute/docusaurus-plugin-godoc`.');
  lines.push('To regenerate manually:');
  lines.push('');
  lines.push('```bash');
  lines.push('cd docusaurus');
  lines.push('npm run gen-godoc');
  lines.push('```');

  return lines.join('\n');
}

function renderCommandsPage(commandTree) {
  const lines = [];

  lines.push('---');
  lines.push('title: Commands Reference');
  lines.push('description: "Auto-generated command reference"');
  lines.push('---');
  lines.push('');
  lines.push('# Commands Reference');
  lines.push('');
  lines.push('{/* Auto-generated by @vantagecompute/docusaurus-plugin-godoc. Do not edit manually. */}');
  lines.push('');

  if (commandTree.description) {
    lines.push(commandTree.description);
    lines.push('');
  }

  if (commandTree.commands.length > 0) {
    lines.push('## Available Commands');
    lines.push('');
    lines.push('| Command | Description |');
    lines.push('|---------|-------------|');
    for (const cmd of commandTree.commands) {
      lines.push(`| \`${commandTree.name} ${cmd.name}\` | ${cmd.description} |`);
    }
    lines.push('');
  }

  if (commandTree.flags.length > 0) {
    lines.push('## Global Flags');
    lines.push('');
    lines.push('```');
    for (const flag of commandTree.flags) {
      lines.push(flag);
    }
    lines.push('```');
  }

  return lines.join('\n');
}

module.exports = {renderPackagePage, renderIndexPage, renderCommandsPage};
